function randomGreeting(name, years) {
  const ageText = years ? `, исполняется ${years} лет` : '';
  const template = TEMPLATES[Math.floor(Math.random() * TEMPLATES.length)];
  return template.replace('{name}', name).replace('{age}', ageText);
}

